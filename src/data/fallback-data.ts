// Horai dynamic calculator
export function getHoraiList(dayName: string): HoraiItem[] {
  // Ordered sequence of Planets in Horai: Sun -> Venus -> Mercury -> Moon -> Saturn -> Jupiter -> Mars -> Sun...
  const planetsOrder = ["சூரியன்", "சுக்கிரன்", "புதன்", "சந்திரன்", "சனி", "வியாழன்", "செவ்வாய்"];
  
  // Starting planet for each day of the week
  const dayStartPlanetIndex: Record<string, number> = {
    "sunday": 0, "ஞாயிறு": 0,
    "monday": 3, "திங்கள்": 3,
    "tuesday": 6, "செவ்வாய்": 6,
    "wednesday": 2, "புதன்": 2,
    "thursday": 5, "வியாழன்": 5,
    "friday": 1, "வெள்ளி": 1,
    "saturday": 4, "சனி": 4
  };

  const planetStatus: Record<string, 'good' | 'bad' | 'neutral'> = {
    "வியாழன்": "good",
    "சுக்கிரன்": "good",
    "புதன்": "good",
    "சந்திரன்": "neutral",
    "சூரியன்": "neutral",
    "செவ்வாய்": "bad",
    "சனி": "bad"
  };

  const startIdx = dayStartPlanetIndex[dayName.toLowerCase()] ?? 3; // Default Monday
  const list: HoraiItem[] = [];
  
  // Return Horai list for 12 daytime hours starting at 6:00 AM
  for (let i = 0; i < 12; i++) {
    const planetIdx = (startIdx + i) % 7;
    const planet = planetsOrder[planetIdx];
    const hourStart = 6 + i;
    const ampmStart = hourStart >= 12 ? "PM" : "AM";
    const hourEnd = 7 + i;
    const ampmEnd = hourEnd >= 12 ? "PM" : "AM";
    
    const displayHourStart = hourStart > 12 ? hourStart - 12 : hourStart;
    const displayHourEnd = hourEnd > 12 ? hourEnd - 12 : hourEnd;
    
    list.push({
      time: `${displayHourStart}:00 ${ampmStart} - ${displayHourEnd}:00 ${ampmEnd}`,
      planet,
      status: planetStatus[planet]
    });
  }

  return list;
}
